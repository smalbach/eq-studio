/**
 * A run as one self-contained HTML page: to attach to a CI run, mail or archive.
 *
 * Everything is inline — styles, the little script that filters the table — and a
 * Content-Security-Policy forbids any request, so the page opens the same offline, from a mail
 * attachment or years later. Light and dark follow the reader's system; printed, every case
 * detail is expanded and the filters disappear. Without JavaScript the page is complete: the
 * script only filters.
 *
 * The run is masked (`mask.ts`) before a single value is written.
 */
import type { Locale } from "../types.ts";
import { tr } from "../i18n.mjs";
import { maskSecrets } from "./mask.ts";
import { failedAssertions, loadSummary, onlyLatency, type ReportCase, type ReportContext, type ReportRun, type ReportStep } from "./model.ts";

const esc = (value: unknown) => String(value ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#39;");

const BODY_PREVIEW = 6_000;
const pretty = (value: unknown) => {
  if (value === undefined || value === null || value === "") return "";
  let text = typeof value === "string" ? value : JSON.stringify(value, null, 2);
  if (typeof value === "string") { try { text = JSON.stringify(JSON.parse(value), null, 2); } catch { /* not JSON: as it is */ } }
  return text.length > BODY_PREVIEW ? `${text.slice(0, BODY_PREVIEW)}\n… (${text.length - BODY_PREVIEW})` : text;
};

const seconds = (ms: number | null | undefined) => ms == null ? "—" : ms < 1000 ? `${Math.round(ms)} ms` : `${(ms / 1000).toFixed(1)} s`;

