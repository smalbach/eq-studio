/** Filters the table by text and status; opens every case before printing. */
const SCRIPT = `
(function(){
  var q=document.getElementById("q"),s=document.getElementById("s"),rows=[].slice.call(document.querySelectorAll("#cases tbody tr")),count=document.getElementById("count");
  function apply(){var text=(q.value||"").toLowerCase(),status=s.value,shown=0;rows.forEach(function(row){var ok=(!status||row.getAttribute("data-status")===status)&&(!text||row.getAttribute("data-text").indexOf(text)>=0);row.hidden=!ok;if(ok)shown++;});count.textContent=shown+" / "+rows.length;}
  if(q){q.addEventListener("input",apply);s.addEventListener("change",apply);apply();}
  window.addEventListener("beforeprint",function(){[].forEach.call(document.querySelectorAll("details"),function(d){d.open=true;});});
})();
`;

function verdictBadge(status: string, words: Texts) {
  const css = status === "passed" ? "v-passed" : status === "failed" || status === "error" ? "v-failed" : "v-other";
  return `<span class="verdict ${css}">${esc(words.verdict[status] ?? status.toUpperCase())}</span>`;
}

const tile = (value: unknown, label: string, css = "") => `<div class="tile"><b class="${css}">${esc(value)}</b><span>${esc(label)}</span></div>`;

function stepHtml(step: ReportStep, words: Texts) {
  const assertions = step.assertions.map((assertion) => {
    const css = assertion.informative ? "a-info" : assertion.pass ? "a-pass" : "a-fail";
    return `<tr><td class="${css}">${assertion.pass ? "✓" : assertion.informative ? "·" : "✗"}</td><td>${esc(assertion.label)}</td><td>${esc(assertion.detail)}</td></tr>`;
  }).join("");
  const request = pretty(step.requestBody);
  const response = pretty(step.responseBody);
  return `<div class="step">
<div><span class="m">${esc(step.method)}</span> <code>${esc(step.url)}</code>${step.step ? ` <span class="label">· ${esc(step.step)}</span>` : ""}</div>
<div class="label">${esc(words.received)}: <b>${esc(step.status ?? words.noResponse)}</b> · ${esc(seconds(step.durationMs))}${step.latency?.budgetMs != null ? ` · p95 ${esc(step.latency.p95)} ms / ${esc(step.latency.budgetMs)} ms` : ""}</div>
${step.error ? `<div class="a-fail">${esc(step.error)}</div>` : ""}
${assertions ? `<table><thead><tr><th></th><th>${esc(words.assertions)}</th><th></th></tr></thead><tbody>${assertions}</tbody></table>` : ""}
${request || response ? `<div class="grid2">${request ? `<div><div class="label">${esc(words.request)}</div><pre>${esc(request)}</pre></div>` : "<div></div>"}${response ? `<div><div class="label">${esc(words.response)}</div><pre>${esc(response)}</pre></div>` : ""}</div>` : ""}
</div>`;
}

function failureHtml(item: ReportCase, words: Texts) {
  const blocked = item.status === "blocked";
  const warning = !blocked && onlyLatency(item);
  const firstFailure = (item.steps ?? []).flatMap((step) => failedAssertions(step).map((assertion) => `${assertion.label}: ${assertion.detail}`))[0];
  return `<details class="case${blocked ? " blocked" : warning ? " warning" : ""}" open data-case="${esc(`${item.operationId}:${item.scenarioId}`)}">
<summary><span class="m">${esc(item.method)}</span> <code>${esc(item.path)}</code> · <b>${esc(item.name)}</b> <span class="label">(${esc(item.operationId)}:${esc(item.scenarioId)})</span>${warning ? ` <span class="pill s-blocked">${esc(words.latencyOnly)}</span>` : ""}</summary>
<div class="case-body">
<div class="label">${esc(words.expected)}: <b>${esc(item.expectedStatus)}</b> · ${esc(seconds(item.durationMs))}${firstFailure ? ` · <span class="a-fail">${esc(firstFailure)}</span>` : ""}</div>
${blocked ? `<p>${esc(words.blockedNote)}</p>` : ""}
${(item.steps ?? []).map((step) => stepHtml(step, words)).join("")}
</div></details>`;
}

function casesTable(cases: ReportCase[], words: Texts) {
  const statuses = [...new Set(cases.map((item) => item.status))];
  const rows = cases.map((item) => {
    const search = `${item.operationId} ${item.method} ${item.path} ${item.name} ${item.scenarioId}`.toLowerCase();
    return `<tr data-status="${esc(item.status)}" data-text="${esc(search)}"><td><span class="pill s-${esc(item.status)}">${esc(words.caseStatus[item.status] ?? item.status)}</span></td><td class="m">${esc(item.method)}</td><td><code>${esc(item.path)}</code></td><td>${esc(item.name)}</td><td><code>${esc(item.scenarioId)}</code></td><td class="num">${esc(item.expectedStatus)}</td><td class="num">${esc(seconds(item.durationMs))}</td></tr>`;
  }).join("\n");
  return `<div class="filters"><input id="q" type="search" placeholder="${esc(words.filter)}" aria-label="${esc(words.filter)}"><select id="s" aria-label="${esc(words.status)}"><option value="">${esc(words.all)}</option>${statuses.map((status) => `<option value="${esc(status)}">${esc(words.caseStatus[status] ?? status)}</option>`).join("")}</select><span id="count" class="count label"></span></div>
<table id="cases"><thead><tr><th>${esc(words.status)}</th><th>${esc(words.method)}</th><th>${esc(words.path)}</th><th>${esc(words.case)}</th><th>${esc(words.scenario)}</th><th>${esc(words.expected)}</th><th>${esc(words.duration)}</th></tr></thead><tbody>
${rows}
</tbody></table>`;
}

function loadHtml(run: ReportRun, words: Texts) {
  const { overall, verdict } = loadSummary(run);
  if (!overall) return `<p>${esc(words.noReport)}</p>`;
  const criteria = (verdict?.checks ?? []).map((check) => `<tr><td class="${check.pass ? "a-pass" : check.informative ? "a-info" : "a-fail"}">${check.pass ? "✓" : "✗"}</td><td>${esc(check.label)}</td><td>${esc(check.detail)}</td></tr>`).join("");
  return `<div class="tiles">${tile(overall.completed, words.requests)}${tile(overall.rps.toFixed(1), words.rps)}${tile(`${overall.p50} ms`, "p50")}${tile(`${overall.p95} ms`, "p95")}${tile(`${overall.p99} ms`, "p99")}${tile(`${(overall.errorRate * 100).toFixed(2)} %`, words.errorRate, overall.errorRate > 0 ? "a-fail" : "")}</div>
${criteria ? `<h2>${esc(words.criteria)}</h2><table><tbody>${criteria}</tbody></table>` : ""}`;
}

export function htmlReport(input: ReportRun, context: ReportContext): string {
  const run = maskSecrets(input, context.secrets);
  const ctx = maskSecrets({ environment: context.environment, baseUrl: context.baseUrl, project: context.project }, context.secrets);
  const locale: Locale = context.locale ?? "en";
  const words = texts(locale);
  const generatedAt = context.generatedAt ?? new Date().toISOString();
  const cases = run.cases ?? [];
  const problems = cases.filter((item) => item.status === "failed" || item.status === "blocked").sort((a, b) => (a.status === "failed" ? 0 : 1) - (b.status === "failed" ? 0 : 1));
  const { totals } = run;
  const meta: [string, string | null | undefined][] = [
    [words.environment, ctx.environment], [words.baseUrl, ctx.baseUrl], [words.contract, context.contractVersion],
    [words.started, run.startedAt ?? run.createdAt], [words.finished, run.finishedAt], [words.run, run.id], [words.generated, generatedAt],
  ];
  const body = run.kind === "functional"
    ? `<div class="tiles">${tile(totals.total, words.total)}${tile(totals.passed, words.passed, "a-pass")}${tile(totals.failed, words.failed, totals.failed ? "a-fail" : "")}${tile(totals.blocked, words.blocked)}${tile(seconds(run.durationMs), words.duration)}</div>`
    : `<div class="tiles">${tile(seconds(run.durationMs), words.duration)}</div>${loadHtml(run, words)}`;
  const failures = run.kind === "functional"
    ? `<section id="failures"><h2>${esc(words.failures)} (${problems.length})</h2>${problems.length ? problems.map((item) => failureHtml(item, words)).join("\n") : `<p class="a-pass">${esc(words.noFailures)}</p>`}</section>
<section id="all"><h2>${esc(words.allCases)} (${cases.length})</h2>${casesTable(cases, words)}</section>`
    : "";
  const title = `${ctx.project} · ${run.scope} · ${words.verdict[run.status] ?? run.status}`;
  return `<!doctype html>
<html lang="${locale}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'; script-src 'unsafe-inline'; img-src data:">
<meta name="generator" content="Endpoint Quality${context.toolVersion ? ` ${esc(context.toolVersion)}` : ""}">
<title>${esc(title)}</title>
<style>${STYLE}</style>
</head>
<body>
<main>
<header>
<div class="sub">${esc(words.title)} · ${esc(run.kind === "functional" ? words.functional : words.load)}</div>
<h1>${esc(ctx.project)} · ${esc(run.scope)} ${verdictBadge(run.status, words)}</h1>
</header>
${body}
<dl class="meta">${meta.filter(([, value]) => value).map(([label, value]) => `<dt>${esc(label)}</dt><dd>${esc(value)}</dd>`).join("")}</dl>
${run.error ? `<div class="alert">${esc(run.error)}</div>` : ""}
${failures}
<footer>${esc(words.footer)}</footer>
</main>
<script>${SCRIPT}</script>
</body>
</html>
`;
}
